#!/usr/bin/env bash
# Build the bare-metal wifi firmware: llgo compiles the Go program plus the
# OSAL C files (LLGoFiles) and links the closed-source blob archives with
# the 13 ROM symbol scripts. No ESP-IDF project, no FreeRTOS anywhere in
# the link.
#
# Target note: esp32s31-flash (the XIP variant of the esp32s31 family). The
# SRAM-only layout cannot hold the blob's ~846 KiB of text+rodata on top of
# the llgo runtime (segment sizes in idfparts/MANIFEST.md); the flash target
# executes text/rodata from the XIP window at 0x40000000 and keeps data/bss
# in SRAM, exactly like the repo's s31-xip tests.
#
# Outputs: wifi.elf and the app image wifi.bin (the emulator flash dump is
# assembled by run-emu.sh from bootloader.bin + partition-table.bin, both
# harvested from the pinned espressif/idf image, see idfparts/MANIFEST.md).
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
PARTS="$DIR/idfparts"
LLGO_BIN="${LLGO_BIN:-/tmp/llgo-wifiosal-bin}"

# One -I is all LLGoFiles' $cflags mechanism reliably carries (the expanded
# env var becomes a single argv element), so idfparts/include-all gathers
# every header the OSAL C compiles against as flat symlinks: sdkconfig.h,
# esp_private/, the esp_wifi type headers, and the shim esp_wifi.h /
# esp_event.h / esp_err.h / esp_netif.h that keep the regulatory copy
# compiling without the esp_event component.
export OSAL_CFLAGS="-I$PARTS/include-all"

# The blob archives ship ilp32f ELF metadata; normalize to the soft-float
# flags the llgo link expects (integer ABI identical; see the script header).
LIBDIR="$PARTS/lib-soft"
if [ ! -f "$LIBDIR/libpp.a" ]; then
    "$DIR/normalize-blobs.sh"
fi

# Generate the link-args file: LLGoPackage expands a $VAR reference into a
# single argv element (see osal/native.go), so the archive and ROM linker
# script paths must be absolute and baked in here.
{
  echo '// Code generated by build.sh from link_args.go.tmpl - DO NOT EDIT.'
  echo '// Absolute paths resolved at generation time (see osal/native.go for'
  echo '// why the env-var form cannot carry them).'
  echo 'package osal'
  echo ''
  printf 'const LLGoPackage = "link: --start-group'
  for lib in core espnow mesh net80211 pp smartconfig wapi phy; do
    printf ' %s/lib%s.a' "$LIBDIR" "$lib"
  done
  printf ' --end-group'
  for f in "$PARTS"/rom/*.ld; do
    printf ' -T %s' "$f"
  done
  printf ' -T %s' "$DIR/osal/sections.ld"
  echo '"'
} > osal/link_args.go

cd "$DIR"
"$LLGO_BIN" build -target esp32s31-flash -obin -o wifi.bin .
ls -la wifi.bin* wifi.elf 2>/dev/null || true
